/* ── motion ──────────────────────────────────────────────────
 * Everything here is progressive: the page is complete without it.
 * `prefers-reduced-motion` short-circuits each effect rather than
 * running it faster, and the CSS mirrors the same guard.
 */

const REDUCED = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

/** Reveal on entry. IntersectionObserver, not a scroll handler — the browser
 *  does the hit-testing off the main thread, and it unobserves once shown. */
function wireReveals() {
  const targets = document.querySelectorAll("[data-reveal]");
  if (REDUCED || !("IntersectionObserver" in window)) {
    targets.forEach((t) => t.classList.add("is-in"));
    document.querySelector(".editorial")?.classList.add("is-in");
    return;
  }
  const io = new IntersectionObserver(
    (entries) => {
      for (const e of entries) {
        if (!e.isIntersecting) continue;
        e.target.classList.add("is-in");
        e.target.closest(".editorial")?.classList.add("is-in");
        io.unobserve(e.target);
        // The stagger delay is for the entrance only; left in place it would
        // also hold back every later hover transition on the same element.
        const node = e.target;
        setTimeout(() => node.style.setProperty("--reveal-delay", "0ms"), 1100);
      }
    },
    { rootMargin: "0px 0px -12% 0px", threshold: 0.12 }
  );
  // Stagger siblings so a row of cards arrives in sequence, not as a slab.
  let i = 0;
  for (const t of targets) {
    t.style.setProperty("--reveal-delay", `${(i % 3) * 90}ms`);
    io.observe(t);
    i += 1;
  }
}

/** Count a KPI up to its value. Reads the rendered text so formatting
 *  (the "96 · 22.9%" composite, "574ms") survives untouched. */
function countUp(node, finalText, value) {
  if (REDUCED || !value || value > 1e7) {
    node.textContent = finalText;
    return;
  }
  const DURATION = 900;
  const start = performance.now();
  const step = (now) => {
    const t = Math.min(1, (now - start) / DURATION);
    const eased = 1 - Math.pow(1 - t, 3);
    if (t < 1) {
      node.textContent = finalText.replace(/^[\d,]+/, nf.format(Math.round(value * eased)));
      requestAnimationFrame(step);
    } else {
      node.textContent = finalText;
    }
  };
  requestAnimationFrame(step);
}

function animateKpis(m) {
  const pairs = [
    ["kpi-calls", m.total_calls],
    ["kpi-denied", m.denied],
    ["kpi-p95", m.ok_latency_p95_ms],
    ["kpi-users", m.unique_users],
  ];
  for (const [id, value] of pairs) {
    const node = $(id);
    countUp(node, node.textContent, value);
  }
}

/** Sticky-nav frosting + a slight hero scale-away. One rAF-throttled
 *  scroll listener for both, writing a CSS custom property. */
function wireScroll() {
  const nav = $("nav");
  const hero = document.querySelector(".hero");
  let queued = false;

  const apply = () => {
    queued = false;
    const y = window.scrollY;
    nav.classList.toggle("is-stuck", y > 24);
    const room = document.documentElement.scrollHeight - window.innerHeight;
    $("progress").style.setProperty("--progress", room > 0 ? Math.min(1, y / room).toFixed(4) : "0");
    if (!REDUCED && hero) {
      // 1 → 0.94 over the first viewport of scrolling.
      const k = Math.min(1, y / (window.innerHeight || 800));
      hero.style.setProperty("--hero-scale", (1 - k * 0.06).toFixed(4));
    }
  };

  window.addEventListener(
    "scroll",
    () => {
      if (queued) return;
      queued = true;
      requestAnimationFrame(apply);
    },
    { passive: true }
  );
  apply();
}

/** Translucent fill under each line, in that line's own colour so the
 *  series identity is unchanged — decoration, not a new encoding. */
function areaFill(ctx, hex) {
  const g = ctx.createLinearGradient(0, 0, 0, 320);
  g.addColorStop(0, `${hex}44`);
  g.addColorStop(1, `${hex}00`);
  return g;
}

/** Pointer-following light on the glass cards. Fine pointers only. */
function wireSpotlight() {
  if (REDUCED || !window.matchMedia("(hover: hover)").matches) return;
  for (const card of document.querySelectorAll(".card")) {
    card.addEventListener("pointermove", (ev) => {
      const r = card.getBoundingClientRect();
      card.style.setProperty("--mx", `${ev.clientX - r.left}px`);
      card.style.setProperty("--my", `${ev.clientY - r.top}px`);
    });
  }
}

/** Mark the nav link for whichever section is under the middle of the screen. */
function wireScrollSpy() {
  if (!("IntersectionObserver" in window)) return;
  const links = new Map();
  for (const a of document.querySelectorAll(".nav__links a")) {
    const target = document.getElementById(a.getAttribute("href").slice(1));
    if (target) links.set(target, a);
  }
  const io = new IntersectionObserver(
    (entries) => {
      for (const e of entries) {
        if (!e.isIntersecting) continue;
        links.forEach((a) => a.classList.remove("is-current"));
        links.get(e.target).classList.add("is-current");
      }
    },
    { rootMargin: "-45% 0px -50% 0px" }
  );
  links.forEach((_, section) => io.observe(section));
}

/* ── explainer: role matrix + request simulator ──────────────
 * Driven by `rbac` and `tools` in the exported payload, which come straight
 * from rbac.py and the tool registry. The stage order and outcomes mirror
 * gateway._pipeline; it is a model of the server, and makes no requests.
 */

const SIM_USERS = {
  alice: { name: "alice", roles: ["viewer"] },
  bob: { name: "bob", roles: ["developer"] },
  carol: { name: "carol", roles: ["admin"] },
  none: null,
};
const ROLE_USER = { viewer: "alice", developer: "bob", admin: "carol" };
const MARK = { pass: "✓", fail: "✕", skip: "–" };

function simulate(payload, userKey, tool, kase) {
  const user = SIM_USERS[userKey];
  const meta = payload.tools[tool];
  const steps = [];
  const step = (id, state, note) => steps.push({ id, state, note });
  const done = (status, code, message) => ({ steps, status, code, message, user, tool });

  if (!user) {
    step("authn", "fail", "no bearer token");
    return done("denied", "UNAUTHENTICATED", "authentication required");
  }
  step("authn", "pass", `${user.name} · ${user.roles.join(", ")}`);

  if (kase === "burst") {
    step("rate", "fail", "bucket is empty");
    return done("error", "RATE_LIMITED", "rate limit exceeded; retry in 1s");
  }
  step("rate", "pass", "token taken");

  const allowed = user.roles.some((r) => (payload.rbac[r] || []).includes(tool));
  if (!allowed) {
    step("authz", "fail", `${user.roles[0]} does not list it`);
    return done("denied", "FORBIDDEN", `your role cannot use ${tool}`);
  }
  step("authz", "pass", "role lists this tool");

  if (kase === "malformed") {
    step("validate", "fail", "schema rejected the input");
    return done("error", "INVALID_ARGUMENTS", "arguments failed validation");
  }
  step("validate", "pass", "arguments accepted");

  if (!meta.idempotent) {
    step("idem", "skip", meta.write ? "done per row inside the bulk tool" : "reads need no key");
  } else if (kase === "retry") {
    step("idem", "pass", "stored result found");
    step("scope", "skip", "not re-run");
    step("upstream", "skip", "not called again");
    return done("ok", null, "stored result replayed (idempotent_replay: true)");
  } else {
    step("idem", "pass", "key reserved");
  }

  if (kase === "scope" && tool !== "slack_list_channels") {
    step("scope", "fail", meta.idempotent ? "not allowlisted · key released" : "not allowlisted");
    return done("denied", "OUT_OF_SCOPE", "that resource is not allowlisted");
  }
  step("scope", "pass", tool === "slack_list_channels" ? "list filtered to allowlisted channels" : "allowlisted");

  if (tool.startsWith("bulk_")) {
    step("upstream", "pass", "dry run: validated, nothing written");
    return done("ok", null, "dry run by default: rows validated, none created");
  }
  step("upstream", "pass", meta.idempotent ? "200 · result stored with the key" : "200");
  return done("ok", null, meta.write ? "written upstream" : "data returned");
}

const wait = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
let simRun = 0;

function renderSimResult(r) {
  const host = $("sim-result");
  host.textContent = "";

  const verdict = el("div", "sim__box");
  verdict.append(el("div", "sim__label", "What the client gets back"));
  const line = el("div", "sim__verdict");
  line.append(statusPill(r.status));
  if (r.code) line.append(el("span", "sim__code", r.code));
  verdict.append(line, el("p", "sim__msg", r.message));

  const row = el("div", "sim__box");
  row.append(el("div", "sim__label", "Audit row written"));
  const body = el("div", "sim__row");
  const fields = [
    ["status", r.status],
    ["error_code", r.code || "null"],
    ["tool", r.tool],
    ["username", r.user ? r.user.name : "anonymous"],
    ["roles", r.user ? r.user.roles.join(",") : ""],
  ];
  for (const [k, v] of fields) {
    const ln = el("div");
    ln.append(el("b", null, `${k}: `), document.createTextNode(v));
    body.append(ln);
  }
  row.append(body);
  host.append(verdict, row);
}

async function runSim(payload) {
  const token = ++simRun;
  const flow = $("flow");
  const stages = [...flow.querySelectorAll(".stage")];
  flow.classList.add("has-run");
  for (const s of stages) {
    s.classList.remove("is-active", "is-pass", "is-fail", "is-skip", "is-unreached");
    s.querySelector(".stage__mark").textContent = "";
    s.querySelector("[data-note]").textContent = "";
  }
  $("sim-result").textContent = "";
  $("flow-audit").classList.remove("is-flash");

  const userKey = $("sim-user").value;
  const tool = $("sim-tool").value;
  const r = simulate(payload, userKey, tool, $("sim-case").value);

  const reached = new Set();
  for (const st of r.steps) {
    const node = flow.querySelector(`[data-stage="${st.id}"]`);
    reached.add(st.id);
    if (!REDUCED) {
      node.classList.add("is-active");
      await wait(st.state === "skip" ? 220 : 430);
      if (token !== simRun) return;   // a newer run took over
      node.classList.remove("is-active");
    }
    node.classList.add(`is-${st.state}`);
    node.querySelector(".stage__mark").textContent = MARK[st.state];
    node.querySelector("[data-note]").textContent = st.note;
  }
  for (const s of stages) {
    if (!reached.has(s.dataset.stage)) s.classList.add("is-unreached");
  }
  void $("flow-audit").offsetWidth;   // restart the flash animation
  $("flow-audit").classList.add("is-flash");
  renderSimResult(r);

  document.querySelectorAll(".cell.is-current").forEach((c) => c.classList.remove("is-current"));
  if (r.user) {
    document
      .querySelector(`.cell[data-role="${r.user.roles[0]}"][data-tool="${tool}"]`)
      ?.classList.add("is-current");
  }
}

function renderMatrix(payload) {
  const roles = Object.keys(payload.rbac);
  const count = (t) => roles.filter((r) => payload.rbac[r].includes(t)).length;
  const tools = Object.keys(payload.tools).sort((a, b) => count(b) - count(a) || a.localeCompare(b));

  const head = el("tr");
  head.append(el("th", null, "Tool"));
  for (const r of roles) head.append(el("th", null, r));
  document.querySelector("#matrix thead").replaceChildren(head);

  const body = document.querySelector("#matrix tbody");
  body.textContent = "";
  let i = 0;
  for (const t of tools) {
    const tr = el("tr");
    const name = el("td", "tool-name", t);
    const write = payload.tools[t].write;
    name.append(el("span", write ? "tag tag--write" : "tag", write ? "write" : "read"));
    tr.append(name);
    for (const r of roles) {
      const yes = payload.rbac[r].includes(t);
      const btn = el("button", yes ? "cell cell--yes" : "cell", yes ? "✓" : "✕");
      btn.type = "button";
      btn.dataset.role = r;
      btn.dataset.tool = t;
      btn.style.setProperty("--i", String(i));
      btn.setAttribute("aria-label", `${r}: ${t} is ${yes ? "allowed" : "refused"}. Run it.`);
      btn.addEventListener("click", () => {
        $("sim-user").value = ROLE_USER[r] || "none";
        $("sim-tool").value = t;
        $("sim-case").value = "normal";
        $("flow").scrollIntoView({ behavior: REDUCED ? "auto" : "smooth", block: "center" });
        setTimeout(() => runSim(payload), REDUCED ? 0 : 550);
      });
      const td = el("td");
      td.append(btn);
      tr.append(td);
      i += 1;
    }
    body.append(tr);
  }
}

function wireSimulator(payload) {
  const select = $("sim-tool");
  for (const t of Object.keys(payload.tools)) {
    const opt = el("option", null, t);
    opt.value = t;
    select.append(opt);
  }
  select.value = "github_create_issue" in payload.tools ? "github_create_issue" : select.options[0].value;
  $("sim").hidden = false;
  $("sim-run").addEventListener("click", () => runSim(payload));

  // Play one request the first time the pipeline scrolls into view.
  if (REDUCED || !("IntersectionObserver" in window)) return;
  const io = new IntersectionObserver(
    (entries) => {
      if (!entries.some((e) => e.isIntersecting)) return;
      io.disconnect();
      if (!$("flow").classList.contains("has-run")) runSim(payload);
    },
    { threshold: 0.25 }
  );
  io.observe($("flow"));
}

