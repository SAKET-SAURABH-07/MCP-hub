async function main() {
  // Gates every reveal rule in the stylesheet: without JS nothing is ever
  // hidden, so a script failure can't blank the page.
  document.documentElement.classList.add("js");

  applyChartDefaults();
  wireRepoLink();
  wireScroll();
  // Before the fetch: the reveals are viewport-driven, not data-driven, and an
  // early return on a load failure must not leave the page hidden.
  wireReveals();
  wireSpotlight();
  wireScrollSpy();
  let payload;
  try {
    const res = await fetch(DATA_URL, { cache: "no-store" });
    if (!res.ok) throw new Error(`${res.status} ${res.statusText}`);
    payload = await res.json();
  } catch (err) {
    showError(
      `Could not load ${DATA_URL} (${err.message}). Generate it with: ` +
      `python scripts/export_metrics.py --db data/demo_audit.db --source demo`
    );
    return;
  }

  const m = payload.metrics;
  renderBanner(payload);
  renderKpis(m);
  renderServices(m);
  $("generated").textContent = `Generated ${payload.generated_at} · ${payload.source} data`;

  // The explainer needs only the role table, so it works on an empty log too.
  if (payload.rbac && payload.tools) {
    renderMatrix(payload);
    wireSimulator(payload);
  } else {
    $("matrix-note").textContent = "Role data is missing from this snapshot. Re-run scripts/export_metrics.py.";
  }

  if (!m.total_calls) {
    showError("The audit log is empty — run the server or scripts/seed_demo.py, then export again.");
    return;
  }

  renderTimeline(m);
  renderTools(m);
  renderCodes(m);
  renderToolTable(m);
  renderRecent(payload.recent, "all");
  wireFilters(payload.recent);

  animateKpis(m);
}

main();
