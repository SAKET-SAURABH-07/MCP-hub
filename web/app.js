function horizontalBar(canvasId, labels, values, label) {
  return new Chart($(canvasId), {
    type: "bar",
    data: {
      labels,
      datasets: [{
        label,
        data: values,
        backgroundColor: COLORS.accent,
        borderRadius: 4,
        borderSkipped: "start",
        barPercentage: 0.78,
        categoryPercentage: 0.84,
        maxBarThickness: 26,   // keeps a 2-bar chart from drawing slabs
      }],
    },
    options: {
      indexAxis: "y",
      responsive: true,
      maintainAspectRatio: false,
      layout: { padding: { right: 44 } },
      plugins: {
        legend: { display: false },     // single series — the card title names it
        tooltip: { padding: 10, displayColors: false },
      },
      scales: {
        x: { display: false, beginAtZero: true, grace: "8%" },
        y: {
          grid: { display: false },
          border: { display: false },
          ticks: {
            font: { size: 11, family: "JetBrains Mono, monospace" },
            autoSkip: false,
            // Narrow screens clip long tool names from the left, which turns
            // "jira_create_issue" into "ira_create_issue" — worse than useless.
            // Truncate from the right instead; the tooltip and the table below
            // both still carry the full name.
            callback(value) {
              const label = this.getLabelForValue(value);
              // ~420px is where the longest tool name stops fitting; above it
              // 30 chars clears every name in the registry untouched.
              const max = this.chart.width < 420 ? 15 : 30;
              return label.length > max ? `${label.slice(0, max - 1)}…` : label;
            },
          },
        },
      },
    },
    plugins: [barValueLabels],
  });
}

