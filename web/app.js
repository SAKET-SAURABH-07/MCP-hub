const $ = (id) => document.getElementById(id);

function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

function fmtMs(ms) {
  if (ms === null || ms === undefined) return "—";
  return ms >= 1000 ? `${(ms / 1000).toFixed(2)}s` : `${Math.round(ms)}ms`;
}

function fmtBucket(bucket, daily) {
  // bucket looks like 2026-11-15T04:00Z
  const d = new Date(bucket.replace("Z", ":00Z"));
  if (Number.isNaN(d.getTime())) return bucket;
  return daily
    ? d.toLocaleDateString("en-US", { month: "short", day: "numeric", timeZone: "UTC" })
    : d.toLocaleString("en-US", { month: "short", day: "numeric", hour: "numeric", timeZone: "UTC" });
}

/** Hourly buckets get unreadable past a few days; roll up to days when there are many. */
function condenseTimeline(timeline) {
  if (timeline.length <= 72) return { points: timeline, daily: false };
  const byDay = new Map();
  for (const b of timeline) {
    const day = b.bucket.slice(0, 10) + "T00:00Z";
    const acc = byDay.get(day) || { bucket: day, ok: 0, denied: 0, error: 0, total: 0 };
    acc.ok += b.ok; acc.denied += b.denied; acc.error += b.error; acc.total += b.total;
    byDay.set(day, acc);
  }
  return { points: [...byDay.values()], daily: true };
}

/* Direct value labels at the end of each horizontal bar, so the numbers are
 * readable without hovering and the chart has a text fallback on screen. */
const barValueLabels = {
  id: "barValueLabels",
  afterDatasetsDraw(chart) {
    const { ctx } = chart;
    ctx.save();
    ctx.font = "500 11px Inter, sans-serif";
    ctx.fillStyle = COLORS.text;
    ctx.textBaseline = "middle";
    for (const meta of chart.getSortedVisibleDatasetMetas()) {
      meta.data.forEach((bar, i) => {
        const v = chart.data.datasets[meta.index].data[i];
        if (!v) return;
        ctx.textAlign = "left";
        ctx.fillText(nf.format(v), bar.x + 8, bar.y);
      });
    }
    ctx.restore();
  },
};

